"""Write a synthetic testing dataset as upload-ready CSV files (the portal's Data → Upload format).

    python scripts/export_test_dataset.py                    # 300 customers → submission/testing_dataset/
    python scripts/export_test_dataset.py --customers 1000 --out somewhere/

Everything is generated by app/data/generator.py (synthetic people, orders, carts, points). The hidden traits the
generator uses to simulate behaviour are not exported, exactly like a real business's export. The files are
checked with the same validator the portal uses before they are written.
"""

import argparse
import csv
import io
import sys
from datetime import datetime, time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.config import ROOT_DIR, TENANTS_DIR  # noqa: E402
from app.data.generator import IST, generate, load_catalog  # noqa: E402
from app.ingest.csv_import import FILES, parse_files  # noqa: E402

CATALOG = TENANTS_DIR / "shopkart" / "catalog.yaml"


def _dt(value) -> str:
    return value.strftime("%Y-%m-%d %H:%M")


def build(n_customers: int, seed: int) -> dict[str, list[dict]]:
    today = datetime.now(IST).date()
    ds = generate(CATALOG, n_customers=n_customers, seed=seed, as_of=today, ref_prefix="C")
    labels = {k: v.get("label", k) for k, v in load_catalog(CATALOG)["categories"].items()}
    cust_ref = {c["id"]: c["external_ref"] for c in ds.customers}
    sku = {p["id"]: p["sku"] for p in ds.products}
    order_ref = {o["id"]: f"O{o['id']:06d}" for o in ds.orders}

    customers = [{
        "customer_id": c["external_ref"], "name": c["name"], "signup_date": c["signup_date"].isoformat(),
        "city": c["city"], "phone": f"9{c['id']:09d}",
        "email": f"{c['name'].lower().replace(' ', '.')}.{c['id']}@example.com",
        "birthday": c["birthday"].isoformat() if c.get("birthday") else "", "gender": c["gender"],
    } for c in ds.customers]
    products = [{"sku": p["sku"], "name": p["name"], "category": labels[p["category"]], "price": p["price"],
                 "margin_pct": p["margin_pct"], "brand": p["brand"]} for p in ds.products]
    orders = [{"order_id": order_ref[o["id"]], "customer_id": cust_ref[o["customer_id"]], "created_at": _dt(o["created_at"]),
               "status": o["status"], "discount_amount": o["discount_amount"], "points_redeemed": o["points_redeemed"],
               "payment_method": o["payment_method"]} for o in ds.orders]
    items = [{"order_id": order_ref[i["order_id"]], "sku": sku[i["product_id"]], "quantity": i["quantity"],
              "unit_price": i["unit_price"], "returned": "yes" if i["returned"] else "no"} for i in ds.order_items]
    carts = [{"customer_id": cust_ref[c["customer_id"]], "created_at": _dt(c["created_at"]), "value": c["value"],
              "category": labels.get(c["top_category"], c["top_category"]), "status": c["status"],
              "items_count": c["items_count"]} for c in ds.carts]
    points = [{"customer_id": cust_ref[p["customer_id"]], "created_at": _dt(p["created_at"]), "points": p["delta"],
               "expires_at": p["expires_at"].strftime("%Y-%m-%d") if p.get("expires_at") else ""}
              for p in ds.points_ledger]
    return {"customers": customers, "products": products, "orders": orders, "order_items": items, "carts": carts,
            "points": points}


def to_csv(name: str, rows: list[dict]) -> bytes:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=[*FILES[name].required, *FILES[name].optional], lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue().encode("utf-8")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--customers", type=int, default=300)
    ap.add_argument("--seed", type=int, default=2026)
    ap.add_argument("--out", type=Path, default=ROOT_DIR / "submission" / "testing_dataset")
    args = ap.parse_args()

    files = {name: to_csv(name, rows) for name, rows in build(args.customers, args.seed).items()}
    report = parse_files(files, datetime.combine(datetime.now(IST).date(), time(23, 59), IST))
    if not report.ok:
        sys.exit("The generated files don't pass the upload checks:\n" + "\n".join(report.errors))
    args.out.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (args.out / f"{name}.csv").write_bytes(data)
    print(f"Wrote {args.out} — passes the upload checks: " +
          ", ".join(f"{v:,} {k}" for k, v in report.counts.items()))
    for w in report.warnings:
        print("  note:", w)


if __name__ == "__main__":
    main()
